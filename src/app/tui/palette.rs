/// Background color for the app based on theme.
pub(crate) fn app_background(theme: UiTheme) -> Color {
    if theme.is_light() {
        Color::Rgb(250, 250, 250)
    } else {
        Color::Rgb(17, 21, 27)
    }
}

/// Background color for sidebar based on theme.
pub(crate) fn sidebar_background(theme: UiTheme) -> Color {
    if theme.is_light() {
        Color::Rgb(243, 243, 243)
    } else {
        Color::Rgb(22, 27, 34)
    }
}

/// Background color for chat area based on theme.
pub(crate) fn chat_background(theme: UiTheme) -> Color {
    if theme.is_light() {
        Color::Rgb(255, 255, 255)
    } else {
        Color::Rgb(17, 21, 27)
    }
}
